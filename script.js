let language = "en";
const languageButton = document.getElementById("languageButton");
const menuButton = document.getElementById("menuButton");
const mobileNav = document.getElementById("mobileNav");
const dialog = document.getElementById("previewDialog");
const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");

function setLanguage(nextLanguage) {
  language = nextLanguage;
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[language][element.dataset.i18n];
    if (value) element.textContent = value;
  });
  languageButton.textContent = language === "en" ? "中文" : "English";
  languageButton.setAttribute("aria-label", language === "en" ? "Switch to Chinese" : "切换到英文");
  document.title = language === "en"
    ? "韩景宸 | Han Jingchen | Hin Sothun — Web & Digital Portfolio"
    : "韩景宸 | Han Jingchen | Hin Sothun — 网站与数字作品集";
  localStorage.setItem("portfolioLanguage", language);
}

languageButton.addEventListener("click", () => setLanguage(language === "en" ? "zh" : "en"));

function closeMenu() {
  menuButton.setAttribute("aria-expanded", "false");
  mobileNav.hidden = true;
  document.body.classList.remove("menu-open");
}

menuButton.addEventListener("click", () => {
  const open = menuButton.getAttribute("aria-expanded") === "true";
  menuButton.setAttribute("aria-expanded", String(!open));
  mobileNav.hidden = open;
  document.body.classList.toggle("menu-open", !open);
});
mobileNav.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));

document.querySelectorAll(".filter").forEach((button) => {
  button.addEventListener("click", () => {
    const category = button.dataset.filter;
    document.querySelectorAll(".filter").forEach((item) => item.classList.toggle("active", item === button));
    document.querySelectorAll(".project-card").forEach((card) => {
      const visible = category === "all" || card.dataset.category === category;
      card.classList.toggle("is-hidden", !visible);
    });
  });
});

function buildTable(item) {
  const head = document.getElementById("previewHead");
  const body = document.getElementById("previewBody");
  head.replaceChildren(); body.replaceChildren();
  const headerRow = document.createElement("tr");
  item.head.forEach((text) => { const cell = document.createElement("th"); cell.textContent = text; headerRow.append(cell); });
  head.append(headerRow);
  item.rows.forEach((row) => {
    const tableRow = document.createElement("tr");
    row.forEach((text) => { const cell = document.createElement("td"); cell.textContent = text; tableRow.append(cell); });
    body.append(tableRow);
  });
}

document.querySelectorAll("[data-preview]").forEach((button) => {
  button.addEventListener("click", () => {
    const item = previews[button.dataset.preview];
    document.getElementById("previewTitle").textContent = item.title[language];
    document.getElementById("dialogDownload").href = `files/${item.file}`;
    buildTable(item);
    dialog.showModal();
  });
});
document.getElementById("dialogClose").addEventListener("click", () => dialog.close());
