const revealItems = document.querySelectorAll(".reveal");
if (reducedMotion.matches || !("IntersectionObserver" in window)) {
  revealItems.forEach((item) => item.classList.add("visible"));
} else {
  const observer = new IntersectionObserver((entries, revealObserver) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) { entry.target.classList.add("visible"); revealObserver.unobserve(entry.target); }
    });
  }, { threshold: .12, rootMargin: "0px 0px -35px" });
  revealItems.forEach((item) => observer.observe(item));
}

const header = document.querySelector(".site-header");
const progressBar = document.getElementById("progressBar");
function updateScrollUI() {
  const scrollTop = window.scrollY;
  const pageHeight = document.documentElement.scrollHeight - window.innerHeight;
  header.classList.toggle("scrolled", scrollTop > 8);
  progressBar.style.transform = `scaleX(${pageHeight > 0 ? scrollTop / pageHeight : 0})`;
}
window.addEventListener("scroll", updateScrollUI, { passive: true });
updateScrollUI();

const heroStage = document.getElementById("heroStage");
if (!reducedMotion.matches) {
  heroStage.addEventListener("pointermove", (event) => {
    const rect = heroStage.getBoundingClientRect();
    const x = ((event.clientX - rect.left) / rect.width - .5) * 14;
    const y = ((event.clientY - rect.top) / rect.height - .5) * 14;
    heroStage.style.setProperty("--tx", `${x}px`);
    heroStage.style.setProperty("--ty", `${y}px`);
  });
  heroStage.addEventListener("pointerleave", () => {
    heroStage.style.setProperty("--tx", "0px"); heroStage.style.setProperty("--ty", "0px");
  });
}

